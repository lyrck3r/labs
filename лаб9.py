"""
    Введення користувачем тексту(рядка)
    first_three = text[:3] - виведення перших 3-х символів рядка
    last_three = text[-3:] - виведення останніх 3-х символів рядка
    even_index_chars = text[::2] - виведення символів з парними індексами
    [::2] - перше(початковий елемент), друге(по який елемент рядка), третє(2-крок ітерації рядка)
"""
text = input("Введіть текст: ")
first_three = text[:3]
last_three = text[-3:]
even_index_chars = text[::2]

# Виведення інформації
print(f"Перші 3 символи тексту: {first_three}")
print(f"Останні 3 символи тексту: {last_three}")
print(f"Символи з парними індексами: {even_index_chars}")

"""
    Введення інформації користувачем
    lengh = len(text) - визначення кількості символів в рядку
    Виведення інформації
"""
